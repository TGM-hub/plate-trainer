"""Build data/frontmap.js (outline paths of US, Canada and Mexico units) for the "Front plates" map.

Usage: python tools/build_frontmap.py ne_10m_admin_1_states_provinces.geojson
Input: Natural Earth 1:10m admin-1 (public domain), from
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_10m_admin_1_states_provinces.geojson
Needs: pip install shapely
The rules (which unit needs a front plate) live in data/frontplates.js, edited by hand.
"""
import json, math, sys
from shapely.geometry import shape, Polygon, MultiPolygon
from shapely.ops import unary_union, transform  # noqa: deprecated alias, still works

COUNTRIES = {'USA', 'CAN', 'MEX', 'PRI', 'VIR'}
RENAME = {'US-DC': 'District of Columbia', 'MX-DIF': 'Mexico City', 'MX-MEX': 'State of Mexico'}
KEEP_TINY = {'US-DC', 'US-RI', 'US-PR', 'US-VI', 'US-DE', 'CA-PE', 'MX-TLA', 'MX-DIF', 'MX-MOR', 'MX-AGU', 'MX-COL'}
W = 1000          # viewBox width
TOL_PX = 0.9      # simplification tolerance, in px
MIN_AREA_PX = 3   # drop islets smaller than this (px²), except the main polygon

# Albers equal-area conic, standard parallels 20°N / 60°N, centred on 100°W
p1, p2, p0, l0 = map(math.radians, (20, 60, 40, -100))
n = (math.sin(p1) + math.sin(p2)) / 2
C = math.cos(p1) ** 2 + 2 * n * math.sin(p1)
r0 = math.sqrt(C - 2 * n * math.sin(p0)) / n
def albers(lon, lat):
    r = math.sqrt(C - 2 * n * math.sin(math.radians(lat))) / n
    t = n * (math.radians(lon) - l0)
    return r * math.sin(t), -(r0 - r * math.cos(t))
def proj(xs, ys, zs=None):
    pts = [albers(x, y) for x, y in zip(xs, ys)]
    return [p[0] for p in pts], [p[1] for p in pts]

feats = json.load(open(sys.argv[1], encoding='utf8'))['features']
units = {}
for f in feats:
    pr = f['properties']
    if pr.get('adm0_a3') not in COUNTRIES: continue
    code = pr.get('iso_3166_2') or ''
    if code.endswith('~'):
        if pr['adm0_a3'] != 'VIR': continue   # small disputed bits
        code = 'US-VI'
    g = shape(f['geometry'])
    # Aleutians west of 180° are stored at positive longitudes: drop them
    parts = [p for p in (g.geoms if isinstance(g, MultiPolygon) else [g]) if p.bounds[0] < 0]
    g = unary_union(parts)
    name = RENAME.get(code) or ('US Virgin Islands' if code == 'US-VI' else pr['name_en'])
    u = units.setdefault(code, {'code': code, 'name': name, 'geoms': []})
    u['geoms'].append(transform(proj, g))

allg = unary_union([gg for u in units.values() for gg in u['geoms']])
minx, miny, maxx, maxy = allg.bounds
s = W / (maxx - minx); H = round((maxy - miny) * s)
fit = lambda xs, ys, zs=None: ([(x - minx) * s for x in xs], [(y - miny) * s for y in ys])

out = []
for code, u in sorted(units.items()):
    g = transform(fit, unary_union(u['geoms']))
    polys = sorted(g.geoms if isinstance(g, MultiPolygon) else [g], key=lambda p: -p.area)
    kept = [polys[0]] + [p for p in polys[1:] if p.area >= MIN_AREA_PX]
    d = []
    for p in kept:
        p = p.simplify(TOL_PX if code not in KEEP_TINY else 0.2, preserve_topology=True)
        if p.is_empty: continue
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            if len(pts) < 3: continue
            d.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z')
    c = g.representative_point()
    out.append({'code': code, 'name': u['name'], 'd': ''.join(d), 'cx': round(c.x, 1), 'cy': round(c.y, 1),
                'area': round(g.area)})

js = ('// Generated by tools/build_frontmap.py from Natural Earth 1:10m admin-1 (public domain). Do not edit.\n'
      f'window.FRONT_MAP = {{"w": {W}, "h": {H}, "units": ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '};\n')
open('data/frontmap.js', 'w', encoding='utf8').write(js)
print(len(out), 'units,', round(len(js) / 1024), 'KB, viewBox', W, 'x', H)
