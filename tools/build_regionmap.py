"""Build the outline map of one country's regions for the regional mode.

Usage: python tools/build_regionmap.py <ne_10m_admin_1_states_provinces.geojson> <ADM0_A3> <out.js> <key>
Example: python tools/build_regionmap.py ne10.geojson MEX data/regions/mx-map.js mx
Input: Natural Earth 1:10m admin-1 (public domain). Needs: pip install shapely
Writes REGION_MAPS[key] = {w, h, units: [{code, name, d, cx, cy, area}]}, codes = ISO 3166-2 suffix (e.g. JAL).
"""
import json, math, sys
from shapely.geometry import shape, MultiPolygon
from shapely.ops import unary_union
import shapely
import numpy as np

src, adm0, out, key = sys.argv[1:5]
RENAME = {'MX-DIF': 'Mexico City', 'MX-MEX': 'State of Mexico'}
W, TOL_PX, MIN_AREA_PX = 1000, 0.6, 2

feats = [f for f in json.load(open(src, encoding='utf8'))['features']
         if f['properties'].get('adm0_a3') == adm0 and not (f['properties'].get('iso_3166_2') or '~').endswith('~')]
geoms = {f['properties']['iso_3166_2']: shape(f['geometry']) for f in feats}
minx, miny, maxx, maxy = unary_union(list(geoms.values())).bounds
# Albers equal-area conic fitted to the country: standard parallels at 1/6 and 5/6 of its latitude span
p1, p2 = map(math.radians, (miny + (maxy - miny) / 6, maxy - (maxy - miny) / 6))
p0, l0 = math.radians((miny + maxy) / 2), math.radians((minx + maxx) / 2)
n = (math.sin(p1) + math.sin(p2)) / 2; C = math.cos(p1) ** 2 + 2 * n * math.sin(p1)
r0 = math.sqrt(C - 2 * n * math.sin(p0)) / n
def albers(c):
    lon, lat = np.radians(c[:, 0]), np.radians(c[:, 1])
    r = np.sqrt(C - 2 * n * np.sin(lat)) / n; t = n * (lon - l0)
    return np.column_stack([r * np.sin(t), -(r0 - r * np.cos(t))])
proj = {k: shapely.transform(g, albers) for k, g in geoms.items()}
bx = unary_union(list(proj.values())).bounds
s = W / (bx[2] - bx[0]); H = round((bx[3] - bx[1]) * s)
units = []
for code, g in sorted(proj.items()):
    g = shapely.transform(g, lambda c: (c - [bx[0], bx[1]]) * s)
    polys = sorted(g.geoms if isinstance(g, MultiPolygon) else [g], key=lambda p: -p.area)
    kept = [polys[0]] + [p for p in polys[1:] if p.area >= MIN_AREA_PX]
    d = []
    for p in kept:
        p = p.simplify(TOL_PX, preserve_topology=True)
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            if len(pts) >= 3: d.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z')
    c = g.representative_point()
    name = RENAME.get(code) or next(f['properties']['name_en'] for f in feats if f['properties']['iso_3166_2'] == code)
    units.append({'code': code.split('-')[1], 'name': name, 'd': ''.join(d), 'cx': round(c.x, 1), 'cy': round(c.y, 1), 'area': round(g.area)})
js = (f'// Generated by tools/build_regionmap.py from Natural Earth 1:10m admin-1 (public domain). Do not edit.\n'
      f'(window.REGION_MAPS ||= {{}})["{key}"] = {{"w": {W}, "h": {H}, "units": ' + json.dumps(units, ensure_ascii=False, separators=(',', ':')) + '};\n')
open(out, 'w', encoding='utf8').write(js)
print(len(units), 'units,', round(len(js) / 1024), 'KB, viewBox', W, 'x', H)
